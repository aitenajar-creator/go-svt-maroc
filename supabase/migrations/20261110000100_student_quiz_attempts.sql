-- Go SVT Maroc: durable cloud storage for each student's quiz attempts.
-- Additive migration: does not alter or delete any existing student table or data.

create table if not exists public.student_quiz_attempts (
  id bigint generated by default as identity primary key,
  student_id uuid not null references auth.users(id) on delete cascade,
  attempt_id text not null,
  quiz_id text not null,
  score integer not null check (score >= 0),
  total_questions integer not null check (total_questions > 0),
  percentage smallint not null check (percentage between 0 and 100),
  mistakes jsonb not null default '[]'::jsonb
    check (jsonb_typeof(mistakes) = 'array'),
  attempted_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint student_quiz_attempts_score_valid
    check (score <= total_questions),
  constraint student_quiz_attempts_student_attempt_unique
    unique (student_id, attempt_id)
);

create index if not exists student_quiz_attempts_student_date_idx
  on public.student_quiz_attempts (student_id, attempted_at desc);

create index if not exists student_quiz_attempts_student_quiz_date_idx
  on public.student_quiz_attempts (student_id, quiz_id, attempted_at desc);

alter table public.student_quiz_attempts enable row level security;

drop policy if exists student_quiz_attempts_select_own
  on public.student_quiz_attempts;
create policy student_quiz_attempts_select_own
  on public.student_quiz_attempts
  for select to authenticated
  using (student_id = (select auth.uid()));

drop policy if exists student_quiz_attempts_insert_own
  on public.student_quiz_attempts;
create policy student_quiz_attempts_insert_own
  on public.student_quiz_attempts
  for insert to authenticated
  with check (student_id = (select auth.uid()));

drop policy if exists student_quiz_attempts_update_own
  on public.student_quiz_attempts;
create policy student_quiz_attempts_update_own
  on public.student_quiz_attempts
  for update to authenticated
  using (student_id = (select auth.uid()))
  with check (student_id = (select auth.uid()));

drop policy if exists student_quiz_attempts_delete_own
  on public.student_quiz_attempts;
create policy student_quiz_attempts_delete_own
  on public.student_quiz_attempts
  for delete to authenticated
  using (student_id = (select auth.uid()));

grant select, insert, update, delete
  on public.student_quiz_attempts to authenticated;
grant usage, select
  on sequence public.student_quiz_attempts_id_seq to authenticated;
